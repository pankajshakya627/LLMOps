from __future__ import annotations

from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]


def page(
    title: str, *body: str, kind: str = "text", note: str = "", source: str = ""
) -> dict[str, Any]:
    return {"title": title, "body": list(body), "kind": kind, "note": note, "source": source}


def code(title: str, path: str, marker: str, lines: int, explanation: str) -> dict[str, Any]:
    text = (ROOT / path).read_text().splitlines()
    start = next(i for i, line in enumerate(text) if marker in line)
    return {
        "title": title,
        "body": [explanation],
        "kind": "code",
        "code": "\n".join(text[start : start + lines]),
        "source": path,
        "note": f"Open {path} and locate {marker}. Read the displayed excerpt in context; it is taken directly from the application. {explanation}",
    }


